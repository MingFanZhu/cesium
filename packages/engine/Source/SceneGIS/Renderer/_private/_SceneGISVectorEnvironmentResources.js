import ShaderProgram from "../../../Renderer/ShaderProgram.js";
import definitions from "../../../Shaders/SceneGIS/EnvironmentEffects/SceneGISBrunetonDefinitions.js";
import common from "../../../Shaders/SceneGIS/EnvironmentEffects/SceneGISBrunetonCommon.js";
import runtime from "../../../Shaders/SceneGIS/EnvironmentEffects/SceneGISBrunetonRuntime.js";
import atmosphere from "../../../Shaders/SceneGIS/EnvironmentEffects/SceneGISBrunetonAtmosphere.js";
import shadows from "../../../Shaders/SceneGIS/EnvironmentEffects/SceneGISCloudShadows.js";
import planar from "../../../Shaders/SceneGIS/EnvironmentEffects/SceneGISPlanarEnvironmentLighting.js";
import lighting from "../../../Shaders/SceneGIS/EnvironmentEffects/SceneGISModelEnvironmentLighting.js";
import receiver from "../../../Shaders/SceneGIS/VectorTiles/SceneGISVectorEnvironmentLighting.js";

const globeDefines = [
  "SCENEGIS_GLOBE",
  "COMBINED_SCATTERING_TEXTURES",
  "TRANSMITTANCE_TEXTURE_WIDTH 256",
  "TRANSMITTANCE_TEXTURE_HEIGHT 64",
  "SCATTERING_TEXTURE_R_SIZE 32",
  "SCATTERING_TEXTURE_MU_SIZE 128",
  "SCATTERING_TEXTURE_MU_S_SIZE 32",
  "SCATTERING_TEXTURE_NU_SIZE 8",
  "IRRADIANCE_TEXTURE_WIDTH 64",
  "IRRADIANCE_TEXTURE_HEIGHT 16",
];

/** Owns only material shader variants; environment textures remain borrowed. @private */
function VectorEnvironmentResources(context) {
  this._context = context;
  this._programs = new Map();
}
VectorEnvironmentResources.lightingSource = function (globe) {
  return globe
    ? [definitions, common, runtime, atmosphere, shadows, lighting, receiver]
    : [atmosphere, shadows, planar, lighting, receiver];
};
VectorEnvironmentResources.setProgram = function (command, program) {
  if (command.shaderProgram !== program) {
    // An inactive HDR branch is not regenerated by Scene. Invalidate it when
    // changing the base program, including environment shutdown in LDR.
    command.derivedCommands = {};
    command.shaderProgram = program;
  }
};
VectorEnvironmentResources.prototype.get = function (base, globe, shadowMap) {
  const shadow = shadowMap !== undefined;
  const depth = shadow && shadowMap._usesDepthTexture;
  const soft = shadow && shadowMap.softShadows;
  const cascades = shadow && shadowMap._numberOfCascades > 1;
  const key = `${base.id}:${globe}:${shadow}:${depth}:${soft}:${cascades}`;
  let program = this._programs.get(key);
  if (!program) {
    const fragment = base.fragmentShaderSource.clone();
    fragment.defines.push("SCENEGIS_VECTOR_ENVIRONMENT");
    if (globe) {
      fragment.defines.push(...globeDefines);
    }
    fragment.sources.unshift(
      ...VectorEnvironmentResources.lightingSource(globe),
    );
    if (shadow) {
      fragment.defines.push("SCENEGIS_VECTOR_SHADOWS");
      if (depth) {
        fragment.defines.push("USE_SHADOW_DEPTH_TEXTURE");
      }
      if (soft) {
        fragment.defines.push("USE_SOFT_SHADOWS");
      }
      if (cascades) {
        fragment.defines.push("SCENEGIS_VECTOR_SHADOW_CASCADES");
      }
    }
    program = ShaderProgram.fromCache({
      context: this._context,
      vertexShaderSource: base.vertexShaderSource,
      fragmentShaderSource: fragment,
      attributeLocations: base._attributeLocations,
    });
    try {
      program._bind();
    } catch (error) {
      program.destroy();
      throw error;
    }
    this._programs.set(key, program);
  }
  return program;
};
VectorEnvironmentResources.prototype.destroy = function () {
  for (const program of this._programs.values()) {
    program.destroy();
  }
  this._programs.clear();
};
export default VectorEnvironmentResources;
